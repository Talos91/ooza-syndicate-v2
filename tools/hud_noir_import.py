"""Alpha 24 Neon Noir: drops the art director's cut HUD sprites into the game - each replaces its NoirBox placeholder.

    python tools/hud_noir_import.py "<...>/References/UI direction 2026-11-02 round-3/hud-redo/generated"

Re-runnable; the References are only read. For every part folder `generated/<part>/` holding a `cut-manifest.json`
(the round-3 pack's format: coordinate_order "x,y,width,height", nine_slice_order "left,top,right,bottom"):
    {"sheets": [{"file": "<sheet>.png", "sprites": [{"id": "send_button", "object_rect": [x, y, w, h],
                 "slice": [l, t, r, b] | null, "stretch_axis": "xy" | "x" | "fixed", "drip": <px under the slab>}]}]}
or one PNG per sprite: {"sprites": [{"id": ..., "sprite_file": "send_button.png", "slice": ...}]}.
Sprite ids are the HUD part ids (HUD-PROMPTS.md ## DROP-IN; HudNoir.PRESETS). A player-colour part comes as two
aligned layers: `<id>_fill` (or `<id>`) + `<id>_rim` (pure white, the game tints it) - the rim is paired onto the part.
Writes
    assets/ui/hud_noir/<id>.png, <id>_rim.png      the cut sprites (at 3x the phone shot)
    scripts/hud_noir_data.gd                       PARTS: what HudNoir.box / draw_skill_button read
then run Godot `--import` once (the PNGs get their .import files; mipmaps on for the HUD's ~1/3 draw scale).
"""
import json
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent
OUT = GAME / "assets/ui/hud_noir"


def crop(sheet_path: Path, rect, dst: Path) -> None:
    from PIL import Image                                      # only needed for sheet-based manifests
    with Image.open(sheet_path) as im:
        x, y, w, h = rect
        im.crop((x, y, x + w, y + h)).save(dst)


def main(gen: Path) -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    parts = {}
    rims = {}
    for man_path in sorted(gen.glob("*/cut-manifest.json")):
        folder = man_path.parent
        man = json.loads(man_path.read_text(encoding="utf-8"))
        assert man.get("coordinate_order", "x,y,width,height") == "x,y,width,height"
        assert man.get("nine_slice_order", "left,top,right,bottom") == "left,top,right,bottom"
        entries = [(sh, s) for sh in man.get("sheets", []) for s in sh["sprites"]] + [(None, s) for s in man.get("sprites", [])]
        for sheet, s in entries:
            sid = s["id"]
            dst = OUT / f"{sid}.png"
            if sheet is not None:
                crop(folder / sheet["file"], s["object_rect"], dst)
                size = s["object_rect"][2:]
            else:
                dst.write_bytes((folder / s["sprite_file"]).read_bytes())
                from PIL import Image
                with Image.open(dst) as im:
                    size = list(im.size)
            res = f"res://assets/ui/hud_noir/{sid}.png"
            if sid.endswith("_rim"):
                rims[sid[:-4]] = res
                continue
            pid = sid[:-5] if sid.endswith("_fill") else sid
            sl = s.get("slice")
            parts[pid] = {"file": res, "size": size, "slice": sl,
                          "axis": s.get("stretch_axis", "xy") if sl else "fixed", "rim": "", "drip": s.get("drip", 0)}
    for pid, res in rims.items():
        if pid in parts:
            parts[pid]["rim"] = res
        else:
            print(f"rim without a fill: {pid}_rim")
    gd = ["## GENERATED by tools/hud_noir_import.py from References/UI direction 2026-11-02 round-3/hud-redo/generated/<part>/ - do not",
          "## edit; re-run it. PARTS: HUD part id -> file (res:// path of the cut sprite), size [w, h] (px, drawn at 3x the phone shot),",
          "## slice [l, t, r, b] (9-slice margins in px, null: fixed - drawn whole, aspect kept), axis xy | x | fixed, rim (the white",
          "## RIM + GLOW layer of the same cell, tinted per seat / faction; \"\" when the part has none), drip (px of drips under a housing).",
          "## Empty until the art director's sheets land: every part then draws its NoirBox placeholder (HudNoir.PRESETS).",
          ""]
    if not parts:
        gd.append("const PARTS := {}")
    else:
        gd.append("const PARTS := {")
        for pid in sorted(parts):
            p = parts[pid]
            sl = "null" if not p["slice"] else "[%s]" % ", ".join(str(v) for v in p["slice"])
            gd.append('\t"%s": {"file": "%s", "size": [%d, %d], "slice": %s, "axis": "%s", "rim": "%s", "drip": %s},'
                      % (pid, p["file"], p["size"][0], p["size"][1], sl, p["axis"], p["rim"], p["drip"]))
        gd.append("}")
    (GAME / "scripts/hud_noir_data.gd").write_text("\n".join(gd) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(parts)} parts ({len(rims)} rims) -> {OUT.relative_to(GAME)}, scripts/hud_noir_data.gd")
    for imp in OUT.glob("*.png.import"):                      # the HUD draws them at ~1/3: mipmaps on
        t = imp.read_text(encoding="utf-8")
        if "mipmaps/generate=false" in t:
            imp.write_text(t.replace("mipmaps/generate=false", "mipmaps/generate=true"), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
