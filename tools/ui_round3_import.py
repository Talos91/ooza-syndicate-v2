"""Alpha 24 (UI round 3): imports Daniele's coordinate-ready UI pack into the game, driven by its cut-manifest.json.

    python tools/ui_round3_import.py "<...>/References/UI direction 2026-11-02 round-3/generated"

Re-runnable: the pack is the source (References are immutable - this only reads them). Writes
  assets/ui/round3/dark/{A,B,C,G}.png     the four theme atlases, dark      (1536x1024, shared coordinates)
  assets/ui/round3/light/{A,B,C,G}.png    the same four, light               (identical alpha masks)
  assets/ui/round3/icons/<id>_<name>.png  every D / E / F icon on its 160x160 canvas, pure white (tinted by modulate)
  assets/ui/round3/manifest.json          what scripts/ui_skin.gd reads: per sprite its sheet, object_rect, 9-slice
                                          margins [l, t, r, b] (relative to object_rect) and stretch_axis
and, when Godot has imported them once, turns mipmaps on in their .import files (the frames and icons draw at
~0.3-0.5 of their source size; re-run `--import` after).
"""
import json
import shutil
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent
OUT = GAME / "assets/ui/round3"
THEMED = {"A": "frames", "B": "hud", "C": "screens", "G": "lists"}
ICONS = {"D": "interface", "E": "skills", "F": "board"}


def main(pack: Path) -> int:
    man = json.loads((pack / "generation-records/cut-manifest.json").read_text(encoding="utf-8"))
    assert man["coordinate_order"] == "x,y,width,height" and man["nine_slice_order"] == "left,top,right,bottom"
    out = {"version": man["version"], "source": "References/UI direction 2026-11-02 round-3/generated", "sprites": {},
           "icons": {}}
    for d in ("dark", "light", "icons"):
        (OUT / d).mkdir(parents=True, exist_ok=True)
    copied = 0
    for sheet in man["sheets"]:
        letter = sheet["file"].split("-")[2]                   # ooze-ui-A-frames-dark.png -> A
        theme = sheet["theme"]
        if letter in THEMED:
            shutil.copyfile(pack / sheet["file"], OUT / theme / f"{letter}.png")
            copied += 1
            if theme != "dark":                                # one entry per sprite: the coordinates are shared
                continue
            for s in sheet["sprites"]:
                e = {"name": s["name"], "sheet": letter, "rect": s["object_rect"],
                     "slice": s.get("slice"), "axis": s.get("stretch_axis", "fixed") if s.get("slice") else "fixed"}
                if "subparts" in s:
                    e["subparts"] = s["subparts"]
                    e["subpart_slice"] = s.get("subpart_slice")
                out["sprites"][s["id"]] = e
        elif letter in ICONS:
            for s in sheet["sprites"]:
                src = pack / s["sprite_file"]
                canvas = src.parent / "canvas-160" / src.name
                name = f"{s['id']}_{s['name']}.png"
                shutil.copyfile(canvas, OUT / "icons" / name)
                copied += 1
                out["icons"][s["id"]] = {"name": s["name"], "file": "icons/" + name}
    (OUT / "manifest.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    # the same table as GDScript constants (no JSON in the export filter, nothing to parse at run time)
    gd = ["## GENERATED by tools/ui_round3_import.py from the round-3 pack's cut-manifest.json - do not edit; re-run it.",
          "## SPRITES: id -> name, sheet (A / B / C / G: assets/ui/round3/<dark|light>/<sheet>.png), rect = object_rect",
          "## [x, y, w, h], slice = 9-slice margins [l, t, r, b] inside rect (null: fixed size), axis xy | x | fixed.",
          "## ICONS: id -> name, file (assets/ui/round3/<file>, white on a 160 px canvas).",
          "", "const SPRITES := " + json.dumps(out["sprites"], sort_keys=True),
          "", "const ICONS := " + json.dumps(out["icons"], sort_keys=True), ""]
    (GAME / "scripts/ui_round3_data.gd").write_text("\n".join(gd), encoding="utf-8")
    mip = 0
    for imp in OUT.rglob("*.png.import"):                      # (exists after Godot's first import)
        t = imp.read_text(encoding="utf-8")
        if "mipmaps/generate=false" in t:
            imp.write_text(t.replace("mipmaps/generate=false", "mipmaps/generate=true"), encoding="utf-8")
            mip += 1
    print(f"round3: {copied} files, {len(out['sprites'])} sprites, {len(out['icons'])} icons, mipmaps on in {mip} .import")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
